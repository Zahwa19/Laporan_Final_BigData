const STORAGE_KEY_PERIODS = 'broiler_periods_v4';
const STORAGE_KEY_SETTINGS = 'broiler_settings_v4';
const STORAGE_KEY_THEME = 'broiler_theme_v4';

function loadPeriodsData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_PERIODS);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed.p4 && parsed.p1 && parsed.p2 && parsed.p3) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Gagal membaca data dari localStorage, menggunakan default.', e);
  }
  return JSON.parse(JSON.stringify(DEFAULT_PERIODS_DATA));
}

function savePeriodsData(data) {
  try {
    localStorage.setItem(STORAGE_KEY_PERIODS, JSON.stringify(data));
    return true;
  } catch (e) {
    console.error('Gagal menyimpan data ke localStorage:', e);
    return false;
  }
}

function resetPeriodsData() {
  try {
    localStorage.removeItem(STORAGE_KEY_PERIODS);
    localStorage.removeItem(STORAGE_KEY_SETTINGS);
  } catch (e) {}
  return JSON.parse(JSON.stringify(DEFAULT_PERIODS_DATA));
}

function loadSettings() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_SETTINGS);
    if (raw) {
      return Object.assign({}, DEFAULT_SETTINGS, JSON.parse(raw));
    }
  } catch (e) {}
  return Object.assign({}, DEFAULT_SETTINGS);
}

function saveSettings(settings) {
  try {
    localStorage.setItem(STORAGE_KEY_SETTINGS, JSON.stringify(settings));
    return true;
  } catch (e) {
    return false;
  }
}

